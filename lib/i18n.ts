const supportedLngs = Object.keys(resources) as Array<keyof typeof resources>;
const storedLanguage = typeof window !== 'undefined' ? window.localStorage.getItem('inptic-lang') : null;
const detectedLanguage = storedLanguage && supportedLngs.includes(storedLanguage as keyof typeof resources) ? storedLanguage : 'fr';

if (!i18next.isInitialized) {
  i18next.use(initReactI18next).init({
    resources,
    supportedLngs,
    lng: detectedLanguage,
    fallbackLng: 'fr',
    interpolation: {
      escapeValue: false,
    },
    returnEmptyString: false,
    react: {
      useSuspense: false,
    },
  });
}

if (typeof window !== 'undefined' && !supportedLngs.includes(i18next.language as keyof typeof resources)) {
  i18next.changeLanguage(detectedLanguage);
}

if (typeof document !== 'undefined') {
  document.documentElement.lang = i18next.language || detectedLanguage;
}

export { supportedLngs };
export default i18next;
